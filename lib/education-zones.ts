function buildPrimaryDistrictIndex(): Record<string, Record<string, string>> {
  const index: Record<string, Record<string, string>> = {}
  for (const [province, groups] of Object.entries(PRIMARY_ZONE_DISTRICTS)) {
    index[province] = {}
    for (const { zone, districts } of groups) {
      for (const d of districts) index[province][d] = zone
    }
  }
  return index
}
const PRIMARY_DISTRICT_INDEX = buildPrimaryDistrictIndex()

// สพป.-only. Null when the district isn't mapped (shouldn't happen for a
// real อำเภอ once transcription is complete, but fails soft rather than
// throwing — e.g. lib/districts.ts carries two non-อำเภอ entries under
// ราชบุรี/สงขลา that intentionally have no zone).
export function zoneForDistrict(province: string, district: string): string | null {
  return PRIMARY_DISTRICT_INDEX[province]?.[district] ?? null
}

// Single seam every form uses to auto-fill เขต once the user has given
// enough info to resolve it unambiguously. สพป. needs อำเภอ (one province
// splits into multiple zones by district); สพม. only ever needs province
// (a zone always covers whole provinces) — except กรุงเทพมหานคร, its lone
// 2-zone case, which is left for the user to pick manually.
// For the admin reference tab: every สพป. zone for a province, each with
// its full อำเภอ list — including single-zone provinces, whose one zone
// just covers every district in lib/districts.ts's DISTRICTS_BY_PROVINCE.
export function primaryZoneDetails(province: string): { zone: string; districts: string[] }[] {
  const groups = PRIMARY_ZONE_DISTRICTS[province]
  if (groups) return groups
  const zones = zonesFor('primary', province)
  return zones.length === 1 ? [{ zone: zones[0], districts: DISTRICTS_BY_PROVINCE[province] ?? [] }] : []
}

export function autoZone(serviceType: ServiceTypeCode | '', province: string, district: string): string {
  if (!serviceType || !province) return ''
  if (serviceType === 'primary') {
    const zones = zonesFor('primary', province)
    if (zones.length <= 1) return zones[0] ?? '' // single-zone province — no district needed
    return district ? (zoneForDistrict(province, district) ?? '') : ''
  }
  if (serviceType === 'secondary') {
    const zones = zonesFor('secondary', province)
    return zones.length === 1 ? zones[0] : ''
  }
  return ''
}
