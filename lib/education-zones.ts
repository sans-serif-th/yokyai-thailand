function buildSecondaryZones(): Record<string, string[]> {
  const result: Record<string, string[]> = { กรุงเทพมหานคร: ['เขต 1', 'เขต 2'] }
  for (const group of SECONDARY_ZONE_GROUPS) {
    const label = group.join(' ')
    for (const province of group) {
      result[province] = [label]
    }
  }
  return result
}

const SECONDARY_ZONES: Record<string, string[]> = buildSecondaryZones()

export function zonesFor(serviceType: string, province: string): string[] {
  if (serviceType === 'primary') return PRIMARY_ZONES[province] ?? []
  if (serviceType === 'secondary') return SECONDARY_ZONES[province] ?? []
  return [] // vocational (สอศ.): one office per province, no numbered zone
}

export function hasZoneOptions(serviceType: ServiceTypeCode): boolean {
  return serviceType === 'primary' || serviceType === 'secondary'
}

